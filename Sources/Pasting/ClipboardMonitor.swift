import Foundation
import AppKit

final class ClipboardMonitor {
    static let shared = ClipboardMonitor()

    private var timer: Timer?
    private var lastChangeCount: Int = -1
    private var lastFingerprint: String?

    private let concealedType = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    private let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    private init() {}

    func start() {
        lastChangeCount = NSPasteboard.general.changeCount
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            DispatchQueue.main.async { self?.poll() }
        }
        timer?.tolerance = 0.2   // let the OS coalesce wakeups
        if let timer {
            RunLoop.main.add(timer, forMode: .common)
        }
        AppLog.info("Clipboard monitor started (changeCount=\(lastChangeCount))")
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pb = NSPasteboard.general
        let count = pb.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count

        if Store.shared.settings.capturingPaused { return }

        let types = Set(pb.types ?? [])
        if Store.shared.settings.ignoreConcealed ?? true, types.contains(concealedType) || types.contains(transientType) || types.contains(autoGeneratedType) {
            AppLog.info("Skipped concealed/transient pasteboard content")
            return
        }

        if let bid = NSWorkspace.shared.frontmostApplication?.bundleIdentifier,
           Store.shared.settings.ignoredApps?.contains(bid) == true {
            AppLog.info("Skipped capture from ignored app \(bid)")
            return
        }
        // Don't re-capture our own writes (pasting a card back, edits in the search field).
        if NSWorkspace.shared.frontmostApplication?.bundleIdentifier == Bundle.main.bundleIdentifier { return }
        guard let item = captureCurrent(from: pb) else { return }
        if item.contentFingerprint() == lastFingerprint { return }
        lastFingerprint = item.contentFingerprint()
        Store.shared.add(item)
        AppLog.info("Captured \(item.kind.rawValue): \(item.displayTitle.prefix(60))")
    }

    private func frontmostAppInfo() -> (name: String?, bundleID: String?) {
        let app = NSWorkspace.shared.frontmostApplication
        return (app?.localizedName, app?.bundleIdentifier)
    }

    private func captureCurrent(from pb: NSPasteboard) -> ClipItem? {
        let (appName, bundleID) = frontmostAppInfo()

        let fileURLs = (pb.readObjects(forClasses: [NSURL.self], options: [
            .urlReadingFileURLsOnly: true
        ]) as? [URL])?.filter(\.isFileURL) ?? []
        let singleImageFile = fileURLs.count == 1 && Self.isImageFileURL(fileURLs[0])

        // Image bitmap on the pasteboard (preferred for chat apps like WeChat that also
        // expose a TCC-protected file URL we must never store as a preview path).
        if let image = NSImage(pasteboard: pb),
           let tiff = image.tiffRepresentation,
           let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]) {
            let hasUsefulText = (pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty == false)
            let size = image.size
            let looksLikeIcon = size.width <= 64 && size.height <= 64
            // Always take the bitmap when the only file URL is an image (WeChat/QQ/…);
            // otherwise keep the old icon+text guard.
            if singleImageFile || !(hasUsefulText && looksLikeIcon) {
                if let filename = Store.shared.saveImageData(png) {
                    return ClipItem(
                        kind: .image,
                        text: pb.string(forType: .string),
                        imageFilename: filename,
                        sourceAppName: appName,
                        sourceAppBundleID: bundleID
                    )
                }
            }
        }

        // Image file URL with no bitmap: copy bytes into our store while the pasteboard
        // grant is still valid. Never keep an external/container path for QL.
        if singleImageFile {
            if let imageItem = Self.ingestImageFileURLs(fileURLs, appName: appName, bundleID: bundleID) {
                return imageItem
            }
            AppLog.info("Skipped unreadable image file URL: \(fileURLs[0].lastPathComponent)")
            // Fall through — do not store a dead WeChat/container path.
        } else if !fileURLs.isEmpty {
            return ClipItem(
                kind: .file,
                fileURLs: fileURLs.map(\.path),
                sourceAppName: appName,
                sourceAppBundleID: bundleID
            )
        }

        // Color (NSColor pasteboard type)
        if let color = NSColor.fromPasteboard(pb) {
            let hex = color.toHexString()
            return ClipItem(
                kind: .color,
                text: hex,
                colorHex: hex,
                sourceAppName: appName,
                sourceAppBundleID: bundleID
            )
        }

        // Rich text only (no plain string on pasteboard): derive text from RTF/HTML
        if pb.string(forType: .string) == nil {
            let rtf = pb.data(forType: .rtf) ?? pb.data(forType: .rtfd)
            let html = rtf == nil ? pb.data(forType: .html) : nil
            if let plain = RichText.plainText(rtf: rtf, html: html), !plain.isEmpty {
                return ClipItem(kind: .text, text: plain, rtfData: rtf, htmlData: html,
                                sourceAppName: appName, sourceAppBundleID: bundleID)
            }
        }

        // String / URL
        if let str = pb.string(forType: .string)?.trimmingCharacters(in: .whitespacesAndNewlines),
           !str.isEmpty {
            if let hex = Self.parseHexColor(str) {
                return ClipItem(
                    kind: .color,
                    text: str,
                    colorHex: hex,
                    sourceAppName: appName,
                    sourceAppBundleID: bundleID
                )
            }
            if let url = URL(string: str), let scheme = url.scheme?.lowercased(),
               (scheme == "http" || scheme == "https"), url.host != nil {
                return ClipItem(
                    kind: .url,
                    text: str,
                    urlString: str,
                    sourceAppName: appName,
                    sourceAppBundleID: bundleID
                )
            }
            if let urlStr = pb.string(forType: .URL),
               let url = URL(string: urlStr), url.host != nil {
                return ClipItem(
                    kind: .url,
                    text: str,
                    urlString: url.absoluteString,
                    sourceAppName: appName,
                    sourceAppBundleID: bundleID
                )
            }
            let rtf = pb.data(forType: .rtf) ?? pb.data(forType: .rtfd)
            let html = pb.data(forType: .html)
            return ClipItem(
                kind: .text,
                text: str,
                rtfData: rtf,
                htmlData: rtf == nil ? html : nil,
                sourceAppName: appName,
                sourceAppBundleID: bundleID
            )
        }

        if let urlStr = pb.string(forType: .URL), let url = URL(string: urlStr) {
            return ClipItem(
                kind: .url,
                text: urlStr,
                urlString: url.absoluteString,
                sourceAppName: appName,
                sourceAppBundleID: bundleID
            )
        }

        return nil
    }

    /// Image extensions we promote from file-URL pasteboards into our own image store.
    private static let imageExtensions: Set<String> = [
        "png", "jpg", "jpeg", "gif", "webp", "heic", "heif", "tif", "tiff", "bmp", "ico"
    ]

    static func isImageFileURL(_ url: URL) -> Bool {
        imageExtensions.contains(url.pathExtension.lowercased())
    }

    /// Copy a single image file URL into Application Support and return an `.image` item.
    /// Returns nil for multi-file drops or non-images (caller keeps them as `.file`).
    static func ingestImageFileURLs(_ urls: [URL], appName: String?, bundleID: String?) -> ClipItem? {
        guard urls.count == 1, let url = urls.first, isImageFileURL(url) else { return nil }
        // Re-encode via NSImage → PNG so the stored file is always a real PNG under our control.
        if let image = NSImage(contentsOf: url),
           let tiff = image.tiffRepresentation,
           let rep = NSBitmapImageRep(data: tiff),
           let png = rep.representation(using: .png, properties: [:]),
           let filename = Store.shared.saveImageData(png) {
            return ClipItem(
                kind: .image,
                imageFilename: filename,
                sourceAppName: appName,
                sourceAppBundleID: bundleID
            )
        }
        // Raw copy fallback (still names .png; OK for WeChat PNGs).
        if let data = try? Data(contentsOf: url), !data.isEmpty,
           let filename = Store.shared.saveImageData(data) {
            return ClipItem(
                kind: .image,
                imageFilename: filename,
                sourceAppName: appName,
                sourceAppBundleID: bundleID
            )
        }
        return nil
    }

    static func parseHexColor(_ raw: String) -> String? {
        var s = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        if s.hasPrefix("#") { s.removeFirst() }
        guard s.count == 6 || s.count == 8 else { return nil }
        let hexSet = CharacterSet(charactersIn: "0123456789abcdefABCDEF")
        guard s.unicodeScalars.allSatisfy({ hexSet.contains($0) }) else { return nil }
        return "#" + s.uppercased().prefix(6)
    }
}

extension NSColor {
    static func fromPasteboard(_ pasteboard: NSPasteboard) -> NSColor? {
        let type = NSPasteboard.PasteboardType("com.apple.cocoa.pasteboard.color")
        guard let data = pasteboard.data(forType: type) else { return nil }
        return try? NSKeyedUnarchiver.unarchivedObject(ofClass: NSColor.self, from: data)
    }

    func toHexString() -> String {
        guard let rgb = usingColorSpace(.sRGB) else { return "#000000" }
        let r = Int(round(rgb.redComponent * 255))
        let g = Int(round(rgb.greenComponent * 255))
        let b = Int(round(rgb.blueComponent * 255))
        return String(format: "#%02X%02X%02X", r, g, b)
    }

    static func fromHex(_ hex: String) -> NSColor? {
        var s = hex.trimmingCharacters(in: .whitespacesAndNewlines)
        if s.hasPrefix("#") { s.removeFirst() }
        guard s.count == 6, let value = UInt32(s, radix: 16) else { return nil }
        let r = CGFloat((value >> 16) & 0xFF) / 255
        let g = CGFloat((value >> 8) & 0xFF) / 255
        let b = CGFloat(value & 0xFF) / 255
        return NSColor(srgbRed: r, green: g, blue: b, alpha: 1)
    }
}
